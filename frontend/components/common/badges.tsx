import { Database, FlaskConical, Satellite, Upload } from "lucide-react";

import { cn } from "@/lib/utils";
import { SPLIT_LABEL } from "@/lib/format";

const base = "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-0.5 text-xs font-medium whitespace-nowrap";

const DISPOSITION_STYLE: Record<string, string> = {
  CONFIRMED: "border-success/40 bg-success/10 text-success",
  "FALSE POSITIVE": "border-warning/40 bg-warning/10 text-warning",
  CANDIDATE: "border-accent-violet/40 bg-accent-violet/10 text-accent-violet",
};

export function DispositionBadge({ value, className }: { value: string | null | undefined; className?: string }) {
  if (!value) return <span className={cn(base, "border-border text-muted-foreground", className)}>No label</span>;
  return <span className={cn(base, DISPOSITION_STYLE[value] ?? "border-border text-muted-foreground", className)}>{value}</span>;
}

export function SplitBadge({ value }: { value: string }) {
  return <span className={cn(base, "border-border text-muted-foreground")}>{SPLIT_LABEL[value] ?? value}</span>;
}

export type ProvenanceKind = "kaggle" | "mast" | "synthetic" | "user";

const PROVENANCE: Record<ProvenanceKind, { label: string; style: string; Icon: typeof Database; title: string }> = {
  kaggle: { label: "Original Kaggle data", style: "border-primary/40 bg-primary/10 text-primary", Icon: Database,
            title: "Kaggle dataset arashnic/exoplanets: the NASA Exoplanet Archive KOI cumulative table" },
  mast: { label: "Additional genuine astronomical observations", style: "border-success/40 bg-success/10 text-success",
          Icon: Satellite, title: "NASA Kepler long-cadence PDCSAP light curves from the MAST archive" },
  synthetic: { label: "Synthetic demonstration data", style: "border-warning/50 bg-warning/10 text-warning",
               Icon: FlaskConical, title: "Generated by code for illustration. Not an observation." },
  user: { label: "User-uploaded data", style: "border-accent-violet/40 bg-accent-violet/10 text-accent-violet",
          Icon: Upload, title: "Supplied by the user. Its origin is not verified." },
};

export function ProvenanceBadge({ kind, className }: { kind: ProvenanceKind; className?: string }) {
  const { label, style, Icon, title } = PROVENANCE[kind];
  return (
    <span className={cn(base, style, className)} title={title}>
      <Icon className="size-3" aria-hidden="true" />
      {label}
    </span>
  );
}
