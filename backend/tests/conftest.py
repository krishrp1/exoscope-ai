"""Shared test fixtures.

All light curves here are SYNTHETIC test fixtures generated by code. They exist
only to exercise the pipeline deterministically and are never used to train or
evaluate the shipped model.
"""
from __future__ import annotations

import numpy as np
import pytest

from backend.ml.preprocessing import PreprocessConfig, process_light_curve

CADENCE = 29.4244 / (60 * 24)


def make_synthetic_curve(period=3.2, t0=1.1, duration_hours=3.0, depth=0.004, n_days=120.0,
                         noise=2e-4, trend=True, seed=0):
    """Box-shaped transits on a slowly varying baseline (synthetic test fixture)."""
    rng = np.random.default_rng(seed)
    time = np.arange(0, n_days, CADENCE)
    flux = np.full(len(time), 1000.0)
    if trend:
        flux *= 1 + 0.01 * np.sin(2 * np.pi * time / 37.0)
    phase_time = (time - t0 + 0.5 * period) % period - 0.5 * period
    in_transit = np.abs(phase_time) < duration_hours / 48.0
    flux[in_transit] *= 1 - depth
    flux += rng.normal(0, noise * 1000.0, len(time))
    return time, flux


@pytest.fixture
def synthetic_curve():
    return make_synthetic_curve()


