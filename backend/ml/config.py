"""Central paths and constants for the ExoScope AI backend.

Data provenance labels used everywhere (code, docs, UI):
  - "Original Kaggle data": the KOI catalog table from arashnic/exoplanets.
  - "Additional genuine astronomical observations": Kepler long-cadence
    PDCSAP light curves from NASA's MAST archive (public S3 mirror).
  - "Synthetic demonstration data": anything generated by code. Never mixed
    into training or evaluation.
"""
